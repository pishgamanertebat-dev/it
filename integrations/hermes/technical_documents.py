"""Opt-in multi-document routing; fixed IDs, source folders and model scopes."""
from __future__ import annotations
import json
import hashlib
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]

def registered_document_ids(*,manual_only=False):
    models=json.loads((ROOT/'tools/manual_models.json').read_text(encoding='utf-8'))
    result=[]
    for name in sorted(set(models.values())):
        path=ROOT/name/'document_manifest.json'
        if not path.is_file():continue
        for d in json.loads(path.read_text(encoding='utf-8'))['documents']:
            if not manual_only or d['document_type']!='parts_book':result.append(d['document_id'])
    return sorted(set(result))

def resolve_document(folder,metadata,document_id=None):
    folder=Path(folder).resolve()
    manifest_path=folder/'document_manifest.json'
    if not manifest_path.is_file():
        if document_id:raise ValueError('This device has no registered supplemental document')
        return metadata
    manifest=json.loads(manifest_path.read_text(encoding='utf-8'))
    selected=document_id or metadata['document_id']
    matches=[d for d in manifest['documents'] if d['document_id']==selected]
    if len(matches)!=1:raise ValueError('Unknown document_id for selected model')
    d=matches[0]
    if d['document_type']=='parts_book':raise ValueError('Use the separate Parts Book tool and book_id')
    pdf=(ROOT/d['file_path']).resolve(strict=True)
    if pdf.parent!=folder or pdf.suffix.lower()!='.pdf':raise ValueError('Registered PDF outside model folder')
    if hashlib.sha256(pdf.read_bytes()).hexdigest()!=d['sha256']:
        raise ValueError('Registered PDF changed; source review required')
    if selected==metadata.get('document_id'):
        if Path(metadata['manual']).resolve()!=pdf or metadata['pdf_pages']!=d['page_count']:
            raise ValueError('Default manual map differs from document registry')
        return dict(metadata,document_identity=d)
    return dict(manual=str(pdf),pdf_pages=d['page_count'],document_id=selected,document_identity=d,
                sections={},visual_document=True,excluded_pages=[])

def choose_document(folder,metadata,question,explicit=None):
    if explicit:return resolve_document(folder,metadata,explicit)['document_id']
    if metadata.get('scope_policy')!='per_page':return None
    text=question.casefold()
    cabin=any(t in text for t in ('کابین','cabin','x50','touch panel','power board'))
    electrical=any(t in text for t in ('نقشه','مدار','diagram','wiring','x50','b362'))
    if cabin and (electrical or any(t in text for t in ('power board','touch panel'))):return 'roc-l8-cabin-9840042409'
    if electrical and any(t in text for t in ('برق','electrical','wiring','b362')):
        return 'roc-l8-electrical-9840042418'
    return metadata['document_id']

def page_allowed(metadata,page,*,visual=False):
    if page in metadata.get('excluded_pages',[]):return False
    if metadata.get('scope_policy')!='per_page':return True
    models=set(metadata.get('page_models',{}).get(str(page),['UNKNOWN']))
    if 'EXCLUDED' in models:return False
    return bool(models & set(metadata['allowed_models'])) or (visual and models=={'UNKNOWN'})

def restrict_sections(metadata,chosen):
    if metadata.get('scope_policy')!='per_page':return chosen
    return [(key,item) for key,item in chosen if item.get('retrieval_enabled',True) and any(
        page_allowed(metadata,p) for p in range(item['pdf_start'],item['pdf_end']+1))]

def diagram_search(folder,metadata,question,limit=6):
    path=Path(folder)/'diagram_index.json'
    if not path.is_file():return []
    catalogue=json.loads(path.read_text(encoding='utf-8'))
    query=question.casefold()
    tokens=re.findall(r'[a-z]+\d+[a-z]*|[a-z]{3,}|[\u0600-\u06ff]{3,}',query)
    hits=[]
    for record in catalogue['sheets']:
        if record['document_id']!=metadata.get('document_id'):continue
        if not page_allowed(metadata,record['pdf_page'],visual=True):continue
        hay=json.dumps({k:record.get(k) for k in ('drawing_title','keywords_fa','component_identifiers','connector_identifiers','referenced_sheets')},ensure_ascii=False).casefold()
        score=sum((30 if re.search(r'\d',t) else 3) for t in tokens if re.search(r'(?<!\w)'+re.escape(t)+r'(?!\w)',hay))
        if not score:continue
        hits.append((score,record))
    hits.sort(key=lambda x:(-x[0],x[1]['pdf_page']))
    return [dict(r,metadata_is_evidence=False,image_inspection_required=True) for _,r in hits[:limit]]

def image_evidence_packet(packet, media, session_id):
    """Opt-in native image content using Hermes' existing multimodal contract.

    Only PNGs generated by this session's registered-source operations qualify.
    No arbitrary image path, auxiliary provider, OCR or generic file tool.
    """
    import base64
    from integrations.hermes.technical_media import _validated_page
    if not media or len(media)>4:
        raise ValueError('Select one to four actual source images for model inspection')
    # The installed AIAgent._tool_result_content_for_active_model owns the
    # provider capability gate, including learned in-session image rejections.
    # Do not re-read a potentially different auxiliary model from a worker thread.
    payloads=[];total=0
    for value in media:
        path=Path(value[6:] if value.startswith('MEDIA:') else value)
        resolved,data,_=_validated_page(path,session_id)
        total+=len(data)
        if total>8*1024**2:
            raise ValueError('Image context exceeds 8 MiB; select fewer pages or an evidenced crop')
        payloads.append((resolved,data))
    packet=dict(packet,image_context_status='NATIVE_IMAGES_ATTACHED',
        image_context_note='Inspect the actual attached pixels. Metadata is only routing. If image parts are absent/unreadable, report that limitation; never claim a pin/wire/value from metadata alone.',
        inspected_image_sources=[dict(media=str(path),sha256=hashlib.sha256(data).hexdigest()) for path,data in payloads])
    text=json.dumps(packet,ensure_ascii=False)
    content=[dict(type='text',text=text)]
    for path,data in payloads:
        content.append(dict(type='text',text='Actual source image: '+path.name))
        content.append(dict(type='image_url',image_url=dict(url='data:image/png;base64,'+base64.b64encode(data).decode(),detail='high')))
    return dict(_multimodal=True,content=content,
        text_summary=json.dumps(dict(packet,image_context_status='IMAGES_NOT_VISIBLE_IN_TEXT_FALLBACK',
            image_context_note='This text fallback does not prove image visibility. Do not claim pin/wire inspection; report that real image evidence is unavailable to the model.'),ensure_ascii=False),
        meta=dict(native_vision=True,document_id=packet.get('document_id'),image_count=len(payloads)))
