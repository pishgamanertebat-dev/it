@lru_cache(None)
def segment(word):
    if word in manual:return manual[word]
    if word in lexicon or len(word)<5:return word
    n=len(word);best={0:(0,[])}
    for i in range(n):
        if i not in best:continue
        for j in range(i+2,n+1):
            w=word[i:j]
            if w in lexicon:
                cost=best[i][0]+1+(0.25 if len(w)==2 else 0)
                if j not in best or cost<best[j][0]:best[j]=(cost,best[i][1]+[w])
    return ' '.join(best[n][1]) if n in best and 2<=len(best[n][1])<=4 else word
